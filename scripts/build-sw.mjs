// Runs after `next build`: precaches everything in out/ and writes out/sw.js.
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "out");

async function walk(dir) {
  const files = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) files.push(...(await walk(p)));
    else files.push(p);
  }
  return files;
}

const wanted = (rel) =>
  rel.endsWith(".html") && rel !== "404.html"
    ? true
    : rel.startsWith("_next/static/") ||
      rel.startsWith("icons/") ||
      rel === "manifest.webmanifest";

const all = (await walk(out))
  .map((f) => relative(out, f).split(sep).join("/"))
  .sort();
const files = all.filter(wanted);

const hash = createHash("sha256");
for (const f of files) {
  hash.update(f);
  hash.update(await readFile(join(out, f)));
}
const version = hash.digest("hex").slice(0, 12);

// Paths are relative to the SW's scope so any basePath works. "./" is the app shell.
const precache = files.map((f) => (f === "index.html" ? "./" : f));
if (!precache.includes("./"))
  throw new Error("out/index.html not found; run next build first.");

const sw = `// Generated by scripts/build-sw.mjs. Do not edit.
const VERSION = "hb-${version}";
const PRECACHE = ${JSON.stringify(precache)};
const SCOPE = self.registration.scope;
const url = (p) => new URL(p, SCOPE).href;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(VERSION).then((c) => c.addAll(PRECACHE.map(url))),
  );
});

self.addEventListener("message", (event) => {
  if (event.data === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => k !== VERSION).map((k) => caches.delete(k))),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const u = new URL(req.url);
  if (u.origin !== self.location.origin || !req.url.startsWith(SCOPE)) return;

  if (req.mode === "navigate") {
    // Cache-first: the shell for this version is immutable, so launches are
    // instant even on a weak signal. New versions arrive via the SW update.
    event.respondWith(
      caches.open(VERSION).then(async (cache) => {
        const hit =
          (await cache.match(req, { ignoreSearch: true })) ||
          (await cache.match(url("./")));
        if (hit) return hit;
        return fetch(req).catch(() => Response.error());
      }),
    );
    return;
  }

  event.respondWith(
    caches.open(VERSION).then(async (cache) => {
      const hit = await cache.match(req, { ignoreSearch: true });
      if (hit) return hit;
      const res = await fetch(req);
      if (res.ok) cache.put(req, res.clone());
      return res;
    }),
  );
});
`;

await writeFile(join(out, "sw.js"), sw);
console.log(`sw.js written: ${precache.length} files, version hb-${version}`);
